def excerpt(rel: str, start: str, end: str | None = None, max_lines: int = 60) -> str:
    """A verbatim excerpt of a source file: from the first line containing `start` to the line before `end`."""
    lines = (APP / rel).read_text(encoding="utf-8").splitlines()
    i = next(n for n, ln in enumerate(lines) if start in ln)
    j = len(lines)
    if end:
        j = next((n for n in range(i + 1, len(lines)) if end in lines[n]), len(lines))
    return "\n".join(lines[i:min(j, i + max_lines)])


