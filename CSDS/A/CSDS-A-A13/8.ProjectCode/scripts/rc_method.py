def sec_method_overview(d):
    d.h2("Overall Methodology")
    d.paras(
        "The method turns the seating problem into three smaller, separately checkable problems and wraps them in a pipeline. The "
        "first is *data preparation*: uploaded files are parsed and validated, and the accepted rows become plain data types. The "
        "second is *allocation* (Stage A), which decides which candidates go to which hall and which colour class of the hall's seat grid "
        "each paper uses. The third is *layout* (Stage B), which decides the exact seat of each candidate inside the class that Stage A "
        "gave to the candidate's paper. An independent validator then re-checks the whole plan.",
        "The key design decision is to enforce the most important rule, that no two neighbours write the same paper, **structurally** "
        "rather than by search. If seats are coloured so that seats of one colour are never neighbours, and each paper in a hall is "
        "confined to a single colour, then two candidates of one paper can never be neighbours, whatever Stage B does. The remaining "
        "rules (roll-number gap, accessible seats, one candidate per seat) are constraints of the Stage B model, and the department mix "
        "is a soft objective. Randomness enters in both stages through seeded random weights in the objectives, so the returned plan "
        "is one random member of the set of valid plans.")
    diagram(d, "flowchart")


