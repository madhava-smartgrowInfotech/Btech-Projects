def sec_math(d):
    d.h2("Mathematical Formulation")
    d.p("**Notation.** Let *C* be the candidates of a sitting and *H* the selected halls. Candidate *c* has a paper p(c), a department "
        "d(c), a roll number r(c) with prefix and number, and a flag a(c) that is true when an accessible seat is needed. Hall *h* is a "
        "grid of rows and columns whose usable seats form the set S(h); A(h) is the set of accessible seats.")
    d.h3("Seat graph and colour classes")
    d.p("Two usable seats of a hall are *neighbours* if they are adjacent in a row, a column or, in 8-neighbour mode, a diagonal, "
        "and no aisle lies between them. Blocked seats and aisles only remove edges. The seat at row *i* and column *j* receives the "
        "colour class")
    d.code("kappa(i, j) = 2 * (i mod 2) + (j mod 2)     (8 neighbours: 4 classes)\n"
           "kappa(i, j) = (i + j) mod 2                  (4 neighbours: 2 classes)", "colour classes of the seat grid")
    d.p("**Lemma.** Two different seats of the same class are never neighbours. *Proof.* In 8-neighbour mode, two seats of one class have "
        "the same row parity and the same column parity, so their row difference and their column difference are both even; since the "
        "seats differ, at least one difference is 2 or more, and neighbours differ by at most 1 in each direction. In 4-neighbour mode, "
        "seats of one class have the same parity of i + j, whereas neighbours differ by exactly 1 in i + j. Removing edges (aisles, blocked "
        "seats) cannot create adjacency. The class sizes are therefore the largest sets of seats that can safely hold one paper, and "
        "the *per-paper ceiling* of a hall is its largest class.")
    d.h3("Stage A: allocation")
    d.p("Group candidates by g = (paper, department, accessible need) and let N(g) be the size of group g. The variables are integers "
        "n(h, g) with 0 <= n(h, g) <= min(N(g), capacity(h)), booleans z(h, p, k) meaning that paper p uses class k in hall h, and "
        "integers m(h, p, k) for the number of candidates of paper p seated in class k of hall h. The constraints are:")
    d.code("sum_h n(h,g) = N(g)                      -- every group is fully placed\n"
           "sum_g n(h,g) <= capacity(h)              -- no hall is over capacity\n"
           "sum_k z(h,p,k) <= 1                      -- one class per paper per hall\n"
           "m(h,p,k) <= |S(h,k)| * z(h,p,k)          -- class size bounds the share\n"
           "sum_k m(h,p,k) = sum_{g in p} n(h,g)     -- shares add up to the paper\n"
           "sum_p m(h,p,k) <= |S(h,k)|               -- classes are not over-filled\n"
           "accessible candidates in class k <= |A(h) in k|\n"
           "100 * occupancy(h) <= capacity(h) * peak -- peak fill bound", "Stage A constraints")
    d.p("The first pass minimises a lexicographic objective, with the peak fill weighted most heavily, followed by the largest paper "
        "share and the largest department share of each hall, and a penalty on each (hall, department, class) triple that a "
        "department spans in several classes. The second pass keeps the optimum (primary <= best) and maximises a weighted sum of the z "
        "variables with seeded random integer weights in the range 0 to 999, so which class and hall each paper receives cannot be "
        "predicted. The compact strategy first selects the fewest, largest halls into which a greedy best-fit packing can place every paper.")
    d.h3("Stage B: seat layout of one hall")
    d.p("After a seeded shuffle gives each hall its candidates, the layout of hall h is a boolean model. Let K(c) be the seats of the "
        "class that Stage A assigned to p(c), intersected with A(h) if a(c) is true. The variable x(c, s) is 1 when candidate c sits on "
        "seat s in K(c):")
    d.code("sum_s x(c,s) = 1                       -- one seat per candidate\n"
           "sum_c x(c,s) <= 1                       -- one candidate per seat\n"
           "for each pair (i,j): same roll prefix, |r(i)-r(j)| < gap,\n"
           "    different classes, and every seat s of i:\n"
           "    x(i,s) + sum_{t in N(s)} x(j,t) <= 1 -- roll-gap clause\n"
           "minimise  W * sum(penalties) - sum w(c,s) * x(c,s)\n"
           "    penalty = 1 when two neighbours share a department\n"
           "    w(c,s) = random integer in [0,20),  W = |C(h)| * 20 + 1", "Stage B model")
    d.p("Pairs of candidates in the same class need no roll-gap constraint, because their seats are never neighbours. The weight W makes "
        "department mixing take precedence over the random term, which then chooses among equally good layouts. The model is seeded with "
        "a random hint and solved with one deterministic worker and a deterministic time budget, so the result depends only on the "
        "seed and inputs.")
    d.h3("Why every hard rule holds")
    d.numbered([
        "No seat has two candidates and every candidate has one seat (Stage B constraints).",
        "Same-paper neighbours are impossible: all candidates of one paper in a hall sit in one class (Stage A), and seats of one class "
        "are never neighbours (Lemma). A shared question paper is one paper key, so it is covered.",
        "Roll-number gaps hold for candidates in different classes by the Stage B clauses, and for the same class by the Lemma.",
        "Accessible needs hold because K(c) contains only accessible seats for such candidates.",
        "Independently of this argument, the validator re-checks all four rules on the finished plan, and a plan that fails is never stored.",
    ])
    d.p("Reproducibility follows from deterministic components: sub-seeds are derived from the plan seed with SHA-256, candidates are "
        "processed in a fixed order, and each solver call uses one worker with a deterministic time limit. The plan stores a "
        "fingerprint of the inputs, a hash of the solver result and a hash of the current seating.")


