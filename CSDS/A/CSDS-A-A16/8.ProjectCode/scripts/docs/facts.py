def tests():
    p = os.path.join(EXP, "pytest_results.xml")
    if not os.path.exists(p):
        return None
    r = ET.parse(p).getroot()
    suite = r if r.tag == "testsuite" else r.find("testsuite")
    return {"tests": int(suite.get("tests")), "failures": int(suite.get("failures")), "errors": int(suite.get("errors")),
            "skipped": int(suite.get("skipped")), "seconds": float(suite.get("time")),
            "cases": [(c.get("classname").split(".")[-1], c.get("name")) for c in suite.iter("testcase")]}


TESTS = tests()


