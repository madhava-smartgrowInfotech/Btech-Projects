def mstd(vals, d=2, pct=True):
    m = statistics.mean(vals)
    s = statistics.stdev(vals) if len(vals) > 1 else 0.0
    k = 100 if pct else 1
    return f"{m * k:.{d}f} ± {s * k:.{d}f}"


