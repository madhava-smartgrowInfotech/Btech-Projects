"""
pages/3_📈_Evaluation.py
-------------------------
Displays model evaluation metrics and plots generated by
evaluate.py. Shows nothing fabricated: if evaluate.py hasn't
been run yet, this page clearly says so instead of inventing
numbers.
"""

import json
import sys
from pathlib import Path

sys.path.append(str(Path(__file__).resolve().parent.parent))

import streamlit as st

from src.utils import RESULTS_DIR

st.set_page_config(page_title="Evaluation", page_icon="📈", layout="wide")

st.title("📈 Model Evaluation")

summary_path = RESULTS_DIR / "eval_summary.json"

if not summary_path.exists():
    st.warning(
        "No evaluation results found yet. REQUIRED USER INPUT: after training "
        "a model with train.py, run:\n\n"
        "`python evaluate.py`\n\n"
        "This computes Precision, Recall, mAP@0.5 and mAP@0.5:0.95 from your "
        "actual trained model on the validation/test set and saves them here. "
        "No values are shown until real evaluation has been run."
    )
    st.stop()

with open(summary_path) as f:
    summary = json.load(f)

st.subheader("Evaluation Metrics")
c1, c2, c3, c4 = st.columns(4)
c1.metric("Precision", f"{summary['precision']:.3f}")
c2.metric("Recall", f"{summary['recall']:.3f}")
c3.metric("mAP@0.5", f"{summary['map50']:.3f}")
c4.metric("mAP@0.5:0.95", f"{summary['map50_95']:.3f}")

st.divider()

st.subheader("Evaluation Plots")
plot_files = {
    "Confusion Matrix": "confusion_matrix.png",
    "Normalized Confusion Matrix": "confusion_matrix_normalized.png",
    "Precision Curve": "P_curve.png",
    "Recall Curve": "R_curve.png",
    "Precision-Recall Curve": "PR_curve.png",
    "F1 Curve": "F1_curve.png",
    "Training Results (loss/mAP over epochs)": "results.png",
}

found_any = False
cols = st.columns(2)
i = 0
for label, filename in plot_files.items():
    plot_path = RESULTS_DIR / filename
    if plot_path.exists():
        found_any = True
        with cols[i % 2]:
            st.markdown(f"**{label}**")
            st.image(str(plot_path), use_container_width=True)
        i += 1

if not found_any:
    st.info(
        "Metric plots weren't found in results/. They are generated "
        "automatically by train.py / evaluate.py after a real training run."
    )
