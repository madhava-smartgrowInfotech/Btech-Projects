ABSTRACT = [
    "E-commerce delivery networks route parcels through hubs, so the places where hubs are opened strongly affect cost and delivery time. Hub location is a hard combinatorial "
    "problem, classical models assume a fixed demand, and demand in practice fluctuates between regions and seasons. The base paper by Danach et al. (IEEE Access, 2025) proposes to "
    "forecast demand with a Random Forest and to feed the forecast into a matheuristic that chooses the hubs, and reports improvements on proprietary data.",
    "This project implements that predict-then-optimise framework end to end as HubOptima. Order histories of 90 demand regions over 36 months (a synthetic dataset, because no real data "
    "was available) are cleaned and turned into 19 lag, rolling, calendar and region features; a Random Forest forecasts next-month demand; a capacitated single-allocation hub-location "
    "model is built from the forecast; and a matheuristic (greedy construction, a local search whose moves are screened by a cheap estimate and priced by exact assignment MIPs, and a "
    "kernel search) solves it. Plans are scored on the demand that actually occurred. A FastAPI service with 14 endpoints and a React web application expose forecasting, planning, "
    "method comparison, scalability benchmarking and month-by-month re-optimisation.",
    f"On six held-out months the Random Forest reaches a MAPE of {RF['mape']:.2f}% (R-squared {RF['r2']:.4f}) against 17.6-19.7% for naive forecasters. For October 2025 the proposed plan "
    f"costs INR {P['total_cost'] / 1e6:.1f} M per month with {P['fulfilment_rate'] * 100:.1f}% simulated fulfilment; greedy, k-means, the largest-markets rule and planning without a forecast cost "
    f"{MET['greedy']['cost_vs_proposed_pct']:.1f}%, {MET['kmeans']['cost_vs_proposed_pct']:.1f}%, {MET['largest']['cost_vs_proposed_pct']:.1f}% and {MET['fixed_avg']['cost_vs_proposed_pct']:.1f}% more. "
    f"The matheuristic matches the exact MIP at 90 and 180 nodes and is 3.67% above the exact incumbent at 270 nodes, where the exact MIP did not finish. Re-planning every month gives "
    f"{ROL['adaptive_avg']['fulfilment_rate'] * 100:.1f}% against {ROL['static_avg']['fulfilment_rate'] * 100:.1f}% simulated fulfilment for a static plan. The evidence is synthetic, the forecast "
    "under-called the October peak by 13.2% and left three of six hubs overloaded, and the base paper's real-data results are not reproduced.",
]
