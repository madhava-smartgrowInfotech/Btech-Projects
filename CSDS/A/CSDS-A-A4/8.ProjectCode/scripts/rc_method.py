def excerpt(relpath, start, end=None, max_lines=None):
    """Lines of a source file from the line containing `start` up to (not including) the line containing `end`."""
    lines = (ROOT / relpath).read_text(encoding="utf-8").splitlines()
    i = next(k for k, ln in enumerate(lines) if start in ln)
    j = len(lines)
    if end:
        j = next(k for k in range(i + 1, len(lines)) if end in lines[k])
    out = lines[i:j]
    while out and not out[-1].strip():
        out.pop()
    return "\n".join(out[:max_lines] if max_lines else out)


