def sec_decisions(d):
    d.h2("Implementation Decisions and Reasoning")
    d.table([["Decision", "Reason", "Consequence"],
             ["Single allocation", "Matches the classic p-hub median family [8] and keeps the assignment sub-problem small", "No split flows; a distant region may be served by one far hub"],
             ["Capacity = factor x planned demand / p", "Ties capacity to the forecast so that forecast error shows as overload", "Under-forecast leads to overloaded hubs; fulfilment below 100%"],
             ["Soft SLA by default, hard SLA optional", "A hard SLA can make a plan infeasible (the edge-case test uses 1 hub and a 5 h SLA); a soft SLA still penalises late delivery", "Reliability is reported, not guaranteed"],
             ["Price hub sets with an exact assignment MIP", "Makes every accepted plan optimal for its hub set", "About 14-18 sub-MIPs per search"],
             ["Screen moves with a greedy estimate (6%)", "Avoids pricing the large majority of moves", "A good move whose estimate is poor can be missed"],
             ["First-improvement with restart", "Simple, and re-ranks candidates after each change", "Search is not guaranteed to reach the global optimum"],
             ["Kernel search of 24 candidates", "Gives the exact solver a small enough model to finish", "Result can be slightly worse than the full MIP (3.67% at 270 nodes)"],
             ["Time-based split and no look-ahead", "Mirrors real use: the future is not known", "Only six test months"],
             ["Model trained once; lags updated each month", "Keeps re-optimisation fast (training takes under a second, so retraining is possible but was not done monthly)", "The rolling horizon tests re-forecasting and re-planning, not re-training"],
             ["Files instead of a database", "Small data; artefacts easy to inspect and replace", "No transactions or multi-user access"],
             ["Thin API, shared package", "One implementation for CLI, Flask and FastAPI", "The numbers of all interfaces agree"],
             ["Background jobs in threads", "Comparison and rolling runs take 20 s to a few minutes", "Single process; jobs are lost if the server stops"]],
            "Implementation decisions", widths=[0.26, 0.4, 0.34], font=9)
    d.p("**A caution about in-sample months.** The Random Forest is trained on rows up to June 2025. For planning months *before* July 2025 the 'forecast' is therefore partly in-sample. "
        "All results reported in this document use the six test months (July to December 2025), for which the model saw no data.")
