def sec_math(d):
    d.h2("Mathematical Formulation")
    d.h3("Inputs derived from the data")
    d.p("Regions are indexed i, j = 1..n (n = 90); every region is a candidate hub site. With D_i the planned demand (forecast) of region i:")
    _eq(d, "a = sin^2(dphi/2) + cos(phi_i) cos(phi_j) sin^2(dlambda/2)", None)
    _eq(d, "dist_ij = 1.25 x 2R asin( sqrt(a) ),     R = 6371 km", "1")
    _eq(d, "t_ij = dist_ij / v + h  (i != j),     t_ii = h / 2", "2")
    _eq(d, "c_ij = r dist_ij + lambda t_ij", "3")
    _eq(d, "f_j = F m(tier_j),     m = 1.35, 1.0, 0.75 for tiers 1, 2, 3", "4")
    _eq(d, "C = kappa SUM_i D_i / p", "5")
    d.p(f"with v = 45 km/h, h = 6 h, r = INR 0.04 per order-km, lambda = INR 1.5 per order-hour, F = INR 2,500,000 per month, kappa = 1.25 and p = 6. The haversine formula [{R_HAV}] gives great-circle distance; the factor 1.25 turns it into an approximate road distance.")
    d.h3("Optimisation model")
    d.p("Binary y_j = 1 if a hub is opened at j; binary x_ij = 1 if region i is served by hub j.")
    _eq(d, "minimise   SUM_j f_j y_j  +  SUM_i SUM_j c_ij D_i x_ij", "6")
    _eq(d, "subject to   SUM_j x_ij = 1   for every i", "7")
    _eq(d, "x_ij <= y_j   for all i, j", "8")
    _eq(d, "SUM_i D_i x_ij <= C y_j   for every j", "9")
    _eq(d, "SUM_j y_j <= p", "10")
    _eq(d, "x_ij = 0  whenever t_ij > SLA     (optional hard service level)", "11")
    _eq(d, "x_ij, y_j in {0, 1}", None)
    d.p("Equation (7) gives every region exactly one hub, (8) lets only open hubs serve, (9) is the hub capacity and (10) limits the number of hubs to p. The objective has three parts: a fixed hub cost, a transport cost proportional to distance and a delivery-time penalty. With a *soft* SLA (the default) late deliveries are only "
        "penalised through the time term and reported by the reliability KPI; with a *hard* SLA constraint (11) forbids them, which can make the problem infeasible. Compared with the base "
        "paper's model this one has a single capacity level, no unmet-demand variable and no robust objective.")
    d.h3("Evaluation measures")
    d.p("A plan is a pair (H, a) of the hub set and the assignment a(i). Given the realised demand R_i, the load of hub j is L_j = SUM over i with a(i) = j of R_i, and the "
        "share a hub can serve is s_j = min(1, C / L_j). The KPIs are:")
    _eq(d, "total cost = SUM_{j in H} f_j + SUM_i r dist_{i,a(i)} R_i + SUM_i lambda t_{i,a(i)} R_i", "12")
    _eq(d, "average delivery time = SUM_i t_{i,a(i)} R_i / SUM_i R_i", "13")
    _eq(d, "fulfilment = SUM_i s_{a(i)} R_i / SUM_i R_i", "14")
    _eq(d, "SLA reliability = SUM_i 1[t_{i,a(i)} <= SLA] s_{a(i)} R_i / SUM_i R_i", "15")
    _eq(d, "utilisation of hub j = L_j / C;     overloaded hub: L_j > C", "16")
    d.p("Fulfilment and reliability are *model* quantities: a hub is assumed to process at most C orders, and the excess is counted as not fulfilled. They are not measured deliveries.")
    d.h3("Forecast measures")
    d.p(f"On the test rows, MAE = mean |y - yhat|, RMSE = sqrt(mean (y - yhat)^2), MAPE = 100 x mean( |y - yhat| / max(y, 1) ) and R^2 = 1 - SS_res / SS_tot, following common practice [{R_HYND}].")


