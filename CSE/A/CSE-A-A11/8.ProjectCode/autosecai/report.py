"""Exporters: PR comment (Markdown), SARIF 2.1.0, JSON, CSV."""
from __future__ import annotations

import csv
import io
import json

from .knowledge import SEVERITY_ORDER

ICON = {"critical": "🟣", "high": "🔴", "medium": "🟠", "low": "🟡", "info": "🔵"}
VERDICT_TEXT = {"BLOCK": "🛑 Blocked - security issues must be fixed", "REQUEST_CHANGES": "⚠️ Changes requested",
                "APPROVE": "✅ Approved"}


def to_markdown(r: dict, max_findings: int = 25) -> str:
    s = r["stats"]
    L = [f"## AutoSecAI review - {VERDICT_TEXT[r['verdict']]}", "",
         f"**Risk score:** {r['score']}/100 &nbsp;|&nbsp; **Files:** {s['files']} &nbsp;|&nbsp; "
         f"**+{s['lines_added']}/-{s['lines_removed']}** lines &nbsp;|&nbsp; "
         f"**Critical/High/Medium:** {s['by_severity']['critical']}/{s['by_severity']['high']}/{s['by_severity']['medium']}", "",
         r["summary"], ""]
    fl = [f for f in r["findings"] if f["in_diff"] and SEVERITY_ORDER[f["severity"]] >= 1][:max_findings]
    if fl:
        L += ["| Severity | Finding | Location | CWE |", "|---|---|---|---|"]
        for f in fl:
            L.append(f"| {ICON[f['severity']]} {f['severity']} | {f['title']} | `{f['file']}:{f['line']}` | {f['cwe'] or '-'} |")
        L.append("")
    for f in [f for f in fl if f["category"] == "security"][:10]:
        L += [f"<details><summary><b>{ICON[f['severity']]} {f['title']}</b> - <code>{f['file']}:{f['line']}</code></summary>", "",
              f"**Why it matters:** {f['explanation']}", "", f"**Impact:** {f['impact']}", ""]
        if f["flow"]:
            L += ["**Data flow:** " + " -> ".join(f["flow"]), ""]
        L += [f"**Fix:** {f['remediation']}", ""]
        if f["patch"]:
            L += ["```diff", f["patch"].rstrip(), "```", ""]
        L.append("</details>\n")
    L.append("_Generated by AutoSecAI (multi-agent PR analysis). Findings marked in-diff are on lines changed by this PR._")
    return "\n".join(L)


def to_sarif(r: dict) -> str:
    rules, seen = [], set()
    results = []
    for f in r["findings"]:
        if f["rule_id"] not in seen:
            seen.add(f["rule_id"])
            rules.append({"id": f["rule_id"], "name": f["title"], "shortDescription": {"text": f["title"]},
                          "helpUri": f"https://cwe.mitre.org/data/definitions/{f['cwe'].split('-')[-1]}.html" if f["cwe"] else "",
                          "properties": {"tags": [t for t in (f["cwe"], f["owasp"], f["category"]) if t]}})
        level = {"critical": "error", "high": "error", "medium": "warning", "low": "note", "info": "note"}[f["severity"]]
        results.append({"ruleId": f["rule_id"], "level": level, "message": {"text": f"{f['title']}: {f['explanation']}"},
                        "locations": [{"physicalLocation": {"artifactLocation": {"uri": f["file"]},
                                                            "region": {"startLine": f["line"], "endLine": f["end_line"]}}}]})
    doc = {"version": "2.1.0", "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
           "runs": [{"tool": {"driver": {"name": "AutoSecAI", "version": "2.0.0", "rules": rules}}, "results": results}]}
    return json.dumps(doc, indent=2)


def to_json(r: dict) -> str:
    return json.dumps(r, indent=2, default=str)


def to_csv(r: dict) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["severity", "confidence", "rule", "title", "cwe", "owasp", "file", "line", "function", "in_diff", "category"])
    for f in r["findings"]:
        w.writerow([f["severity"], f["confidence"], f["rule_id"], f["title"], f["cwe"], f["owasp"], f["file"], f["line"],
                    f["function"], f["in_diff"], f["category"]])
    return buf.getvalue()
