"""
Writes docs/REPORT_FACTS.md from the experiment JSON files, the code and the screenshot folder.
Every document built later must agree with this file.

    python scripts/make_report_facts.py
"""

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from scripts.docs import facts as F  # noqa: E402


def pct(x, d=1):
    return f"{x * 100:.{d}f}%"


def exp_rows():
    rows = []
    for key, label in (("exp01_custom_cnn_clahe", "exp01 baseline: project defaults (lr 1e-4), official split"), ("exp02_custom_cnn_tuned", "exp02 tuned recipe, official split (DEPLOYED)"),
                       ("exp03_custom_cnn_patient_split", "exp03 tuned recipe, patient-level re-partition (own test part)"), ("exp04_mobilenetv3small", "exp04 MobileNetV3Small (ImageNet), official split"),
                       ("exp05_custom_cnn_noclahe", "exp05 tuned recipe, no CLAHE, official split")):
        e = F.exp(key)
        if not e:
            rows.append(f"| {label} | not run | | | | | |")
            continue
        t = e["test"]
        b = t["binary_normal_vs_pneumonia"]
        rows.append(f"| {label} | {t['n']} | {pct(t['accuracy'])} | {t['macro_f1']:.3f} | {pct(b['sensitivity'])} | {pct(b['specificity'])} | {e['training']['epochs_run']} ep, best {e['training']['best_epoch']} |")
    return rows


def main():
    L = []
    w = L.append
    w("# Report facts - Pneumonia Detection Using Deep Learning (CSE-A-A12)\n")
    w("Single source of truth for the documentation set. Generated by `scripts/make_report_facts.py` from `experiments/*.json`; "
      "every later document must agree with it. Nothing below was typed by hand except the batch details.\n")
    w("## 1. Batch\n")
    w(f"- Project: {F.TITLE}; batch {F.BATCH_NO} ({F.SECTION}); guide {F.GUIDE} ({F.GUIDE_DESIGNATION} - not recorded)")
    for n, r in F.STUDENTS:
        w(f"- {n} - {r}")
    w(f"- College: {F.COLLEGE} (taken from the institution's template banner and the batch documentary file); academic year {F.YEAR}; principal/HOD names not recorded (placeholders kept)")
    w("- Base paper: " + F.BASE_PAPER + "\n")

    w("## 2. Dataset\n")
    d = (F.DEPLOYED or {}).get("dataset", {})
    w("- Source: Kermany, Zhang, Goldbaum (2018), *Labeled OCT and Chest X-Ray Images for Classification*, Mendeley Data v3, doi 10.17632/rscbjbr9sj.3; licence **CC BY 4.0**; mirror used for download: Hugging Face `ahulikal/chest-xray-pneumonia-mirror` (unmodified `chest_xray.zip`, 1.2 GB).")
    w("- Size: 5,856 JPEG images (paediatric, Guangzhou Women and Children's Medical Center). Official folders: train 5,216 (1,341 normal / 3,875 pneumonia = 2,530 bacterial + 1,345 viral), val 16 (8 / 8), test 624 (234 normal / 390 pneumonia = 242 bacterial + 148 viral).")
    w("- Classes: Normal / Bacterial Pneumonia / Viral Pneumonia; pathogen label from the file name (`person*_bacteria_*`, `person*_virus_*`).")
    if d:
        w(f"- Split used by the main experiment (patient-level 10 % validation from train+val, seed 42): train {d['train']:,} ({d['train_by_class']}), validation {d['validation']:,} ({d['validation_by_class']}), test {d['test']} ({d['test_by_class']}); training patients {d['train_patients']:,}, validation patients {d['validation_patients']}.")
    if F.LEAK:
        lk = F.LEAK
        w(f"- Id overlap: {lk['sharing_patient_id_with_training']} of {lk['test_images']} official test images share an id with train/val (pneumonia files only; 0 of 234 normal). Patient-disjoint subset: {lk['patient_disjoint_images']} images.")
    w("")

    w("## 3. Metrics\n")
    w("Protocol: official test split unless stated; one seed (42) per configuration; CPU only.\n")
    w("| Experiment | test n | 3-class accuracy | macro F1 | pneumonia sensitivity | normal specificity | training |")
    w("|---|---|---|---|---|---|---|")
    L.extend(exp_rows())
    w("")
    M = F.DEPLOYED
    if M:
        t = M["test"]
        w(f"### Deployed model ({F.DEPLOYED_NAME})\n")
        w("| Class | precision | recall | F1 | support |")
        w("|---|---|---|---|---|")
        for c in F.CLASSES:
            p = t["per_class"][c]
            w(f"| {c} | {p['precision']:.3f} | {p['recall']:.3f} | {p['f1']:.3f} | {p['support']} |")
        w(f"\n- Accuracy {t['accuracy']:.4f}; macro P/R/F1 {t['macro_precision']:.3f}/{t['macro_recall']:.3f}/{t['macro_f1']:.3f}; weighted F1 {t['weighted_f1']:.3f}; macro one-vs-rest AUC {t['auc_ovr_macro']:.3f}")
        w(f"- Confusion matrix (rows true, cols predicted, order Normal/Bacterial/Viral): {t['confusion_matrix']}")
        b = t["binary_normal_vs_pneumonia"]
        w(f"- Binary view: TP {b['tp']}, FN {b['fn']}, TN {b['tn']}, FP {b['fp']}; accuracy {b['accuracy']:.4f}, sensitivity {b['sensitivity']:.4f}, specificity {b['specificity']:.4f}, precision {b['precision']:.4f}, F1 {b['f1']:.4f}, AUC {b['auc']:.4f}")
        w(f"- ECE (10 bins) {t['expected_calibration_error']:.4f}; mean confidence {t['mean_confidence']:.4f}")
        w("- Confidence-threshold analysis: " + "; ".join(f"t={r['threshold']:.2f}: kept {r['kept']} ({pct(r['coverage'])}), accuracy {pct(r['accuracy_on_kept']) if r['accuracy_on_kept'] is not None else 'n/a'}" for r in t["confidence_threshold_analysis"]))
        tr = M["training"]
        w(f"- Training: {tr['epochs_run']} epochs run (best {tr['best_epoch']}), {tr['seconds_total']:.0f} s total, {tr['seconds_per_epoch']:.0f} s/epoch, {tr['parameters']:,} parameters, restored-model validation accuracy {tr['val_accuracy_restored_model']:.4f}")
        l = M["latency_ms_mean_cpu"]
        w(f"- Latency (CPU, mean of {l['images_timed']} images, one at a time): preprocess {l['preprocess']:.0f} ms, predict {l['predict']:.0f} ms, Grad-CAM+overlay {l['gradcam_overlay']:.0f} ms, total {l['total_pipeline']:.0f} ms")
    if F.API_LAT:
        a = F.API_LAT
        w(f"- API end-to-end POST /api/predict: {a['requests']} requests, mean {a['mean_ms']:.0f} ms, median {a['median_ms']:.0f} ms, p95 {a['p95_ms']:.0f} ms, max {a['max_ms']:.0f} ms; GET history {a['history_mean_ms']:.0f} ms; GET record {a['record_mean_ms']:.0f} ms")
    w("")

    w("## 4. Architecture summary\n")
    w("- Flask app (`app.py`, port 5000, untouched) + FastAPI layer (`backend/main.py`, port 8312) + React 19/Vite 8 front end (`frontend/`, port 5312, kit V2 Neo Brutal Grid). SQLite `pneumonia_app.db` (table `predictions`, 10 columns); images in `static/uploads` and `static/heatmaps`; weights in `saved_models/`.")
    w("- Pipeline: decode grayscale -> resize 224x224 -> CLAHE (clip 2.5, 8x8) -> Gaussian 3x3 -> RGB, /255 -> CNN (4 conv blocks 32/64/128/256 + BN + MaxPool, GAP, Dense 512 + BN + Dropout .35, Dense 128 + Dropout .25, softmax 3) -> Grad-CAM on `last_conv`, overlay alpha 0.4.")
    if F.MODEL_INFO:
        mi = F.MODEL_INFO
        w(f"- Model: {mi['total_params']:,} parameters ({mi['trainable']:,} trainable, {mi['non_trainable']:,} non-trainable), {mi['float32_mb']} MB float32.")
    w("- Not implemented: U-Net lung segmentation (objective 2), Monte Carlo Dropout, semi-supervised learning.")
    w("- Shipped Grad-CAM cannot reach a nested transfer-learning backbone (verified with MobileNetV3Small): `Output with path 0 is not connected to inputs`.")
    w("- `model/train.py` (original) trains with rescale only (no CLAHE) while inference applies CLAHE; `scripts/train_experiment.py` uses the inference preprocessing.\n")

    w("## 5. Endpoints\n")
    src = open(os.path.join(ROOT, "backend", "main.py"), encoding="utf-8").read()
    for m in re.finditer(r'@api\.(get|post|delete)\("([^"]+)"', src):
        w(f"- `{m.group(1).upper()} {m.group(2)}`")
    w("")

    w("## 6. Tests\n")
    t = F.TESTS or {}
    if t:
        py = t.get("pytest", {})
        w(f"- pytest: {py.get('passed')} passed / {py.get('failed')} failed / {py.get('skipped')} skipped in {py.get('seconds')} s; per file {py.get('per_file')}")
        if "smoke" in t:
            w(f"- smoke test: {t['smoke']['passed']} of {t['smoke']['checks']} checks passed")
        if "ui" in t:
            w(f"- UI verification (360/768/1440 px x light/dark, drawer, dialog, theme, focus, reduced motion): passed = {t['ui']['passed']}")
    else:
        w("- (run `python scripts/run_all_tests.py`)")
    w("")

    w("## 7. Screenshots (1440x900, real data)\n")
    sd = F.SHOTS
    for f in sorted(os.listdir(sd)):
        if f.endswith(".png"):
            w(f"- `docs/screenshots/{f}` ({os.path.getsize(os.path.join(sd, f)) // 1024} KB)")
    w("\n## 8. Diagrams and figures\n")
    for sd in (F.DIAG, F.FIGS):
        if os.path.isdir(sd):
            for f in sorted(os.listdir(sd)):
                if f.endswith(".png"):
                    w(f"- `docs/{os.path.basename(sd)}/{f}`")
    w("\n## 9. Environment\n")
    ep = os.path.join(F.EXP, "environment.json")
    if os.path.exists(ep):
        e = json.load(open(ep))
        w(f"- {e['os']}; {e['cpu']} ({e['cores']} cores / {e['logical_processors']} threads), {e['ram_gb']} GB RAM, {e['gpu']}")
        w(f"- Python {e['python']}, TensorFlow {e['tensorflow']} (Keras {e['keras']}), NumPy {e['numpy']}, OpenCV {e['opencv']}, scikit-learn {e['scikit_learn']}, FastAPI {e['fastapi']}, Uvicorn {e['uvicorn']}, Flask {e['flask']}, Node {e['node']}, npm {e['npm']}")
        w(f"- `requirements.txt` pins: {', '.join(e['pinned_requirements'])} (experiments ran on the system interpreter with the versions above; the shipped model was also re-saved/verified under the pinned TensorFlow, see below)")
    w("\n## 10. Gaps stated plainly\n")
    w("- No U-Net segmentation; no MC Dropout; no semi-supervised learning; no external dataset; one seed per configuration (no confidence intervals); labels from file names; no clinician evaluation; no formal user-acceptance test.")
    w("- Four sample images in `dataset_sample/` come from Wikimedia Commons (CC0/public domain), are partly adult films, and are used only to demonstrate the interface.")
    out = os.path.join(F.DOCS, "REPORT_FACTS.md")
    open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
