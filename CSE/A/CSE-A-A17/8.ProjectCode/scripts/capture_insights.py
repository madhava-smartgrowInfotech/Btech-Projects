"""capture_insights.py - re-takes only the AI Insights screen, retrying while Gemini answers 503 (high demand).

    python scripts/capture_insights.py [--url http://localhost:5317] [--tries 8]

Needs a backend that already has data, a trained model and a domain run (run capture_screens.py first).
"""

import argparse
from pathlib import Path

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parent.parent


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", default="http://localhost:5317")
    ap.add_argument("--tries", type=int, default=8)
    a = ap.parse_args()
    with sync_playwright() as p:
        try:
            b = p.chromium.launch(channel="chrome", headless=True)
        except Exception:
            b = p.chromium.launch(headless=True)
        page = b.new_context(viewport={"width": 1440, "height": 900}, color_scheme="light").new_page()
        page.goto(a.url + "/app/insights", wait_until="load")
        page.wait_for_timeout(1200)
        page.get_by_label("Your question").fill("Which features matter most, and why?")
        for i in range(a.tries):
            page.get_by_role("button", name="Get AI explanation", exact=True).click()
            try:
                page.get_by_text("Generated by Gemini").wait_for(timeout=90000)
                page.wait_for_timeout(1200)
                page.screenshot(path=str(ROOT / "docs" / "screenshots" / "21_insights.png"))
                page.locator("text=Generated by Gemini").first.scroll_into_view_if_needed()
                page.wait_for_timeout(500)
                page.screenshot(path=str(ROOT / "docs" / "screenshots" / "21b_insights-answer.png"))
                print("answered on try", i + 1)
                b.close()
                return 0
            except Exception:
                print("try", i + 1, "no answer, waiting")
                page.wait_for_timeout(15000)
        b.close()
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
