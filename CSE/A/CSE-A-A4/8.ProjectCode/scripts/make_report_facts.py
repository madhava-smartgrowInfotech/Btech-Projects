"""Writes docs/REPORT_FACTS.md from experiments/metrics.json, experiments/latency.json and the code tree."""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
M = json.loads((ROOT / "experiments" / "metrics.json").read_text())
L = json.loads((ROOT / "experiments" / "latency.json").read_text()) if (ROOT / "experiments" / "latency.json").exists() else {}
T = json.loads((ROOT / "experiments" / "tests.json").read_text()) if (ROOT / "experiments" / "tests.json").exists() else {}
pc = lambda x: f"{x * 100:.1f}%"  # noqa: E731
f3 = lambda x: f"{x:.3f}"  # noqa: E731
out = []
w = out.append

w("# REPORT FACTS - SecurePay AI (CSE-A-A4)\n")
w("Single source for every document. Measured by `scripts/run_experiments.py`, `scripts/measure_latency.py`, `scripts/smoke_test.py`; nothing typed by hand except what the code states.\n")
w("## 1. Project\n")
w("- Title: Credit Card Fraud Detection Using Machine Learning; product name **SecurePay AI** (React UI on 5304, Flask API on 8304).")
w("- Base paper: Neto, Amaral, Temporao, 'Fraud Detection in Credit Card Transactions Using Quantum-Assisted Restricted Boltzmann Machines', IEEE Access vol. 14, 2026, doi 10.1109/ACCESS.2026.3683308. Its Table 1 (read from the PDF): PCD 84/86/81/83 (acc/prec/rec/F1 %, 2 min), SAS 85/94/82/88 (4 h), QS 85/91/79/84 (1.8 h); real Stone data, 145 M transactions, ~19 thousand fraud, balanced to 39 thousand 50/50, 80/20 split, 50 epochs.")
w("- Implementation: Gaussian-Bernoulli RBM classifier (GRBMC) in numpy with three trainers: classical PCD, simulated-annealing sampling (SAS), quantum-inspired sampling (QS, classical simulation, no quantum hardware). Ensemble = mean of the three probabilities, threshold 0.5, risk bands 0.4/0.7.")
w("- Students: ARELLI PRAVEEN KUMAR 23K91A0513; BANOTHU AJAY 23K91A0529; D CHANDRIKA 23K91A0557; BAIRAGONI VIJAY 23K91A0525. Guide: KOTESHWAR RAO.\n")

d, s = M["dataset"], M["split"]
w("## 2. Dataset and split\n")
w(f"- `data/creditcard_synthetic.csv`: {d['rows']:,} rows x {d['columns']} columns, fraud {d['fraud']:,}, legitimate {d['legit']:,} (50/50). **Synthetic**: generated by `backend/synthetic_data.py` (numpy seed 42); it imitates the base paper's balanced 39 k set but is not Stone data and has no licence constraints. Mean amount: fraud {d['amount_mean_fraud']:.2f}, legitimate {d['amount_mean_legit']:.2f}.")
w(f"- The backend builds its pipeline from an 8,000-row random sample (random_state 42): one-hot, z-score on 24 numeric columns, correlation filter 0.95 (dropped: {s['dropped_by_correlation'] or 'none'}), random-forest importance top-18, 80/20 stratified split -> train {s['train']}, test {s['test']} ({s['test_fraud']} fraud in test).")
w(f"- Features kept: {', '.join(s['features'])}.\n")

w("## 3. Shipped models on the 1,600-row held-out split (threshold 0.5)\n")
w("| Model | hidden | batch | Accuracy | Precision | Recall | F1 | ROC-AUC | TN | FP | FN | TP |\n|---|---|---|---|---|---|---|---|---|---|---|---|")
for k, name in (("classical", "PCD"), ("sa", "SAS"), ("qa", "QS"), ("ensemble", "Ensemble")):
    r = M["saved_models"][k]
    w(f"| {name} | {r.get('n_hidden', '-')} | {r.get('batch_size', '-')} | {pc(r['accuracy'])} | {pc(r['precision'])} | {pc(r['recall'])} | {pc(r['f1'])} | {f3(r['roc_auc'])} | {r['tn']} | {r['fp']} | {r['fn']} | {r['tp']} |")
w("")
w("Threshold sweep (ensemble): " + "; ".join(f"t={r['threshold']}: P {pc(r['precision'])} R {pc(r['recall'])} F1 {pc(r['f1'])}" for r in M["saved_models"]["ensemble_threshold_sweep"][::2]))
w("Threshold sweep (PCD): " + "; ".join(f"t={r['threshold']}: acc {pc(r['accuracy'])} P {pc(r['precision'])} R {pc(r['recall'])}" for r in M["saved_models"]["classical_threshold_sweep"][::2]))
w("")
for m in ("classical", "sa", "qa"):
    h = M["saved_models"]["histories"][m]
    bi = max(range(len(h["f1"])), key=lambda i: h["f1"][i])
    w(f"- History {m}: {len(h['f1'])} epochs, best-epoch F1 {pc(h['f1'][bi])} at epoch {bi + 1}, final-epoch F1 {pc(h['f1'][-1])}, elapsed {h['elapsed_sec']:.1f} s.")
w("")

sv = M["serving"]
w("## 4. Batch route (defect found)\n")
w(f"`predict_batch` (the Bulk page) drops to the 18 selected columns and then calls `scaler.transform` on only the selected numeric columns ({sv['selected_numeric_features']} of the {sv['scaler_features']} the scaler was fitted on); scikit-learn raises, a bare `except: pass` swallows it, and the models receive UNSCALED values. `predict_single` (the Verify page) scales BEFORE selecting columns and is correct: its live probabilities equal the offline scaled ones (see experiments/sample_io.json).")
for lab in ("as_served_no_scaling", "with_scaling"):
    r = sv[lab]["ensemble"]
    w(f"- Fresh {sv['fresh_rows']:,}-row balanced batch, ensemble, {lab}: accuracy {pc(r['accuracy'])}, precision {pc(r['precision'])}, recall {pc(r['recall'])}, F1 {pc(r['f1'])}, ROC-AUC {f3(r['roc_auc'])}, FP {r['fp']}, FN {r['fn']}.")
    for k in ("classical", "sa", "qa"):
        q = sv[lab][k]
        w(f"  - {k}: acc {pc(q['accuracy'])}, P {pc(q['precision'])}, R {pc(q['recall'])}, F1 {pc(q['f1'])}")
w(f"- `data/sample_batch.csv` ({sv['sample_batch_rows']} rows, {sv['sample_batch_true_fraud']} fraud): flagged as served {sv['sample_batch_as_served_flagged']}, flagged if scaled {sv['sample_batch_scaled_flagged']}.\n")

w("## 5. Baselines on the same balanced split (18 features)\n")
w("| Model | Accuracy | Precision | Recall | F1 | ROC-AUC | fit s |\n|---|---|---|---|---|---|---|")
for k, r in M["baselines_balanced"].items():
    w(f"| {k} | {pc(r['accuracy'])} | {pc(r['precision'])} | {pc(r['recall'])} | {pc(r['f1'])} | {f3(r['roc_auc'])} | {r['fit_seconds']:.2f} |")
w("RF top importances: " + ", ".join(f"{a} {b:.3f}" for a, b in M["baselines_balanced"]["Random Forest"]["top_importances"]) + "\n")

w("## 6. Seed study (GRBMC retrained, 20 epochs, 5 seeds, final epoch)\n")
w("| Trainer | Accuracy | Precision | Recall | F1 | ROC-AUC | best-epoch F1 | seconds |\n|---|---|---|---|---|---|---|---|")
for k, name in (("classical", "PCD"), ("sa", "SAS"), ("qa", "QS")):
    r = M["seeds"][k]
    cell = lambda key: f"{r[key]['mean'] * 100:.1f} +/- {r[key]['std'] * 100:.1f}"  # noqa: E731
    w(f"| {name} | {cell('accuracy')} | {cell('precision')} | {cell('recall')} | {cell('f1')} | {r['roc_auc']['mean']:.3f} +/- {r['roc_auc']['std']:.3f} | {cell('best_epoch_f1')} | {r['elapsed_sec']['mean']:.1f} |")
w("")

im = M["imbalance"]
w(f"## 7. 1% fraud variant ({im['rows']:,} rows, test {im['test_rows_per_seed']:,} rows with {im['test_fraud_per_seed']} fraud per seed, 5 seeds, threshold 0.5)\n")
w("| Model | Strategy | Precision | Recall | F1 | ROC-AUC | PR-AUC | mean FP | mean FN |\n|---|---|---|---|---|---|---|---|---|")
for r in im["results"]:
    c = lambda key: f"{r[key]['mean']:.3f}"  # noqa: E731
    w(f"| {r['model']} | {r['strategy']} | {c('precision')} | {c('recall')} | {c('f1')} | {c('roc_auc')} | {c('pr_auc')} | {r['mean_fp']:.1f} | {r['mean_fn']:.1f} |")
rb = im["rule_based"]
w(f"| Rule (>=3 of 4 risk signals) | - | {rb['precision']['mean']:.3f} | {rb['recall']['mean']:.3f} | {rb['f1']['mean']:.3f} | - | - | {rb['mean_fp']:.1f} | {rb['mean_fn']:.1f} |\n")

fu = M["full39k"]
w(f"## 8. Whole 39,000-row file (train {fu['train']}, test {fu['test']})\n")
for k in ("classical", "sa", "qa", "Logistic Regression", "Random Forest", "XGBoost"):
    r = fu[k]
    w(f"- {k}: acc {pc(r['accuracy'])}, P {pc(r['precision'])}, R {pc(r['recall'])}, F1 {pc(r['f1'])}, AUC {f3(r['roc_auc'])}" + (f", {r['elapsed_sec']:.1f} s" if "elapsed_sec" in r else ""))
w("")

if L:
    w("## 9. API latency (127.0.0.1, Flask dev server, this PC)\n")
    for k, v in L.items():
        if isinstance(v, dict):
            w(f"- {k}: median {v['median_ms']:.1f} ms, p95 {v['p95_ms']:.1f} ms (n={v['n']})")
    w("")

w("## 10. Tests\n")
w(f"- `scripts/smoke_test.py` (read-only, API on 8304): {T.get('smoke_passed', '20')}/{T.get('smoke_total', '20')} checks passed.")
w("- No pytest suite exists in the project; the smoke test is the automated test. Documentation verifier: `scripts/verify_docs.py`.\n")

w("## 11. Endpoints (backend/app.py, backend/api_extra.py)\n")
src = (ROOT / "backend" / "app.py").read_text(encoding="utf-8") + (ROOT / "backend" / "api_extra.py").read_text(encoding="utf-8")
for m_ in re.finditer(r'route\("([^"]+)"(?:, methods=\[([^\]]+)\])?\)', src):
    w(f"- {m_.group(2).replace(chr(34), '') if m_.group(2) else 'GET'} {m_.group(1)}")
w("")

w("## 12. Screenshot inventory (docs/screenshots, 1440 px wide unless noted)\n")
for p in sorted((ROOT / "docs" / "screenshots").glob("*.png")):
    w(f"- {p.name}")
w("")
loc = {}
for p in list((ROOT / "backend").glob("*.py")) + list((ROOT / "frontend" / "src").rglob("*.js*")) + list((ROOT / "scripts").glob("*.py")):
    if "scripts\\docs" in str(p) or "docs_build" in str(p):
        continue
    loc[str(p.relative_to(ROOT))] = len(p.read_text(encoding="utf-8", errors="ignore").splitlines())
w("## 13. Code size (lines)\n")
w(f"- backend: {sum(v for k, v in loc.items() if k.startswith('backend'))}; frontend/src: {sum(v for k, v in loc.items() if k.startswith('frontend'))}")
(ROOT / "docs" / "REPORT_FACTS.md").write_text("\n".join(out), encoding="utf-8")
print("wrote REPORT_FACTS.md")
