def shot_w(path, base=5.6, max_h_in=6.4):
    """Picture width in inches that keeps the height under max_h_in."""
    from PIL import Image

    with Image.open(path) as im:
        w, h = im.size
    return min(base, max_h_in * w / h)


def thr_row(t):
    for r in OFF["thresholds"]:
        if abs(r["threshold"] - t) < 1e-9:
            return r
    raise KeyError(t)


def crypto_row(kind, size, op):
    """Median ms of a crypto benchmark. kind: sc|aes|rsa2048|rsa3072; size like '100 KB'; op: encrypt|decrypt."""
    if kind == "sc":
        return CRY["secure_channel_ecdh_aesgcm"][size][op]["median_ms"]
    if kind == "aes":
        return CRY["aes256gcm_only"][size][op]["median_ms"]
    return CRY["rsa2048_oaep_aesgcm" if kind == "rsa2048" else "rsa3072_oaep_aesgcm"]["sizes"][size][op]["median_ms"]
