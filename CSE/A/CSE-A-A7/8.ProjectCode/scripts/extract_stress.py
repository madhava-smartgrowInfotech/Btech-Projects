"""Stress test for the rule-based report reader (backend/app/services/extract.py).

40 short report fragments written by hand for this check (not generated by make_sample_reports.py). Each carries the set of
flags a clinician would tick. Fragments cover plain statements, negation, abbreviations, OCR run-ons, lab values and
paraphrases the lexicon does not know. Writes experiments/extra/extract_stress.json.

    venv\\Scripts\\python scripts\\extract_stress.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app.services import extract  # noqa: E402

# (category, text, expected flags)
CASES = [
    # plain statements
    ("plain", "Presents with chest pain radiating to the left arm. ECG shows ST elevation in leads II, III and aVF.", {"chest_pain", "st_elevation"}),
    ("plain", "Patient is febrile with productive cough. Chest X-ray: right lower lobe consolidation.", {"fever", "infiltrate"}),
    ("plain", "Sudden severe headache followed by vomiting. CT head shows subarachnoid haemorrhage.", {"severe_headache", "vomiting", "ct_hemorrhage"}),
    ("plain", "Fell from a ladder. X-ray confirms fracture of the left radius.", {"trauma", "fracture"}),
    ("plain", "Right lower quadrant pain with nausea and vomiting since last night.", {"abd_pain", "vomiting"}),
    ("plain", "Facial droop and slurred speech noted by family; right-sided weakness.", {"stroke_signs"}),
    ("plain", "Collapsed at work, brief loss of consciousness. Now drowsy.", {"syncope", "altered_mental"}),
    ("plain", "Massive haematemesis this morning, patient pale.", {"bleeding"}),
    ("plain", "Road traffic accident, laceration on scalp, bleeding controlled with pressure.", {"trauma", "bleeding"}),
    ("plain", "Difficulty breathing since yesterday, known asthma.", {"dyspnea", "copd"}),
    # negation
    ("negation", "Denies chest pain. No shortness of breath. Afebrile.", set()),
    ("negation", "No fever, no vomiting, no abdominal pain.", set()),
    ("negation", "Patient denies syncope but reports chest tightness on exertion.", {"chest_pain"}),
    ("negation", "Negative for fracture on X-ray. No intracranial haemorrhage on CT.", set()),
    ("negation", "Without bleeding or trauma; complains of fever and chills.", {"fever"}),
    ("negation", "Chest pain: absent. Dyspnoea: present.", {"dyspnea"}),
    # abbreviations
    ("abbreviation", "SOB since morning. Known HTN and DM2.", {"dyspnea", "hypertension", "diabetes"}),
    ("abbreviation", "K/c/o CAD, on clopidogrel. Presents with angina.", {"cardiac_hx", "anticoagulant", "chest_pain"}),
    ("abbreviation", "PMH: T2DM, COPD, prior CVA.", {"diabetes", "copd", "prior_stroke"}),
    ("abbreviation", "STEMI on ECG, door to balloon requested.", {"st_elevation"}),
    # OCR run-ons and noise
    ("ocr", "Complains of shortnessofbreath and chestpain.", {"dyspnea", "chest_pain"}),
    ("ocr", "Pat ient has high fever and vomit ing.", {"fever", "vomiting"}),
    ("ocr", "ST elevat ion in V2 to V4.", {"st_elevation"}),   # split word: expected to be missed
    ("ocr", "Severe head ache with confusion.", {"severe_headache", "altered_mental"}),
    # labs
    ("labs", "Troponin: 0.52 ng/mL. Lactate 4.1 mmol/L.", {"lab_troponin_high", "lab_lactate_high"}),
    ("labs", "WBC 15.2, glucose 310 mg/dL, creatinine 2.4.", {"lab_wbc_high", "lab_glucose_abn", "lab_creatinine_high"}),
    ("labs", "Hb 7.8 g/dL. Troponin 0.01.", {"lab_hgb_low"}),
    ("labs", "Glucose 95. WBC 7.4. Creatinine 0.9. Lactate 1.1.", set()),
    ("labs", "Blood sugar 42 mg/dL on arrival.", {"lab_glucose_abn"}),
    # history
    ("history", "Past medical history of atrial fibrillation on warfarin.", {"cardiac_hx", "anticoagulant"}),
    ("history", "Hypertensive, diabetic, previous stroke two years ago.", {"hypertension", "diabetes", "prior_stroke"}),
    ("history", "History of heart failure and stent placement.", {"cardiac_hx"}),
    # paraphrases the lexicon does not contain (expected misses)
    ("paraphrase", "Cannot catch his breath, lips look blue.", {"dyspnea"}),
    ("paraphrase", "Crushing pain in the centre of the chest.", {"chest_pain"}),
    ("paraphrase", "Keeps vomiting everything, belly very sore.", {"vomiting", "abd_pain"}),
    ("paraphrase", "Blood pressure medicine daily; sugar tablets.", {"hypertension", "diabetes"}),
    ("paraphrase", "Not responding to voice, eyes open only to pain.", {"altered_mental"}),
    # mixed narrative
    ("mixed", "58-year-old man, diabetic, with chest pain for 2 hours and diaphoresis. Denies dyspnea. Troponin 1.8. ECG: ST elevation.",
     {"diabetes", "chest_pain", "lab_troponin_high", "st_elevation"}),
    ("mixed", "Child with fever and vomiting for 2 days, drowsy. WBC 18.0. No trauma.", {"fever", "vomiting", "altered_mental", "lab_wbc_high"}),
    ("mixed", "Elderly woman, fall at home, hip fracture on X-ray, on apixaban. No head injury.", {"trauma", "fracture", "anticoagulant"}),
]


def main():
    tp = fp = fn = exact = 0
    by_cat, misses, extras = {}, [], []
    for i, (cat, text, want) in enumerate(CASES, 1):
        got = {f for f, v in extract.parse([{"page": 1, "text": text}])["flags"].items() if v}
        a, b, c = len(got & want), len(got - want), len(want - got)
        tp, fp, fn = tp + a, fp + b, fn + c
        exact += got == want
        s = by_cat.setdefault(cat, {"cases": 0, "tp": 0, "fp": 0, "fn": 0, "exact": 0})
        s["cases"] += 1; s["tp"] += a; s["fp"] += b; s["fn"] += c; s["exact"] += got == want
        if want - got:
            misses.append({"case": i, "category": cat, "missed": sorted(want - got)})
        if got - want:
            extras.append({"case": i, "category": cat, "extra": sorted(got - want)})
    for s in by_cat.values():
        s["precision"] = round(s["tp"] / max(s["tp"] + s["fp"], 1), 3)
        s["recall"] = round(s["tp"] / max(s["tp"] + s["fn"], 1), 3)
    out = {"cases": len(CASES), "expected_flags": tp + fn, "tp": tp, "fp": fp, "fn": fn,
           "precision": round(tp / max(tp + fp, 1), 4), "recall": round(tp / max(tp + fn, 1), 4),
           "cases_read_exactly": exact, "by_category": by_cat, "missed": misses, "spurious": extras,
           "note": "fragments written by the developers for this check; not independent clinical text"}
    dest = ROOT / "experiments" / "extra"
    dest.mkdir(parents=True, exist_ok=True)
    (dest / "extract_stress.json").write_text(json.dumps(out, indent=2))
    print(json.dumps(out, indent=2))


if __name__ == "__main__":
    main()
