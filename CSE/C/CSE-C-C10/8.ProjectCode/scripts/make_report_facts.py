def table(models, keys, names):
    head = "| Model | " + " | ".join(names) + " |\n|---|" + "---|" * len(names) + "\n"
    rows = "".join(f"| {m} | " + " | ".join(pm(v, k) for k in keys) + " |\n" for m, v in models.items())
    return head + rows


