"""Generate docs/REPORT_FACTS.md from the project's own artefacts (documentation run).

Everything here is read from files: experiments/**/metrics.json, the source tree, requirements.txt, the screenshot folder.
    python scripts/make_report_facts.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXP = ROOT / "experiments"
DOCS = ROOT / "docs"


def load(name):
    p = EXP / name / "metrics.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


tts, story, api, tests, sasr = load("tts_asr"), load("story_generation"), load("api_timing"), load("tests"), load("story_asr")
L: list[str] = []


def w(s: str = "") -> None:
    L.append(s)


def f(v, n=3):
    return "n/a" if v is None else (f"{v:.{n}f}" if isinstance(v, float) else str(v))


w("# StoryVox - REPORT FACTS")
w()
w("Single source of facts for the CSE-C-C2 documents. Generated by `scripts/make_report_facts.py`; every number below is read from")
w("`experiments/*/metrics.json`, the source tree or the screenshot folder. Nothing is estimated.")
w()
w("## 1. Project")
w("- Product: **StoryVox** - Multilingual Story Generation and Speech System. Batch CSE-C-C2, API port 8402, web port 5402.")
w("- Students: Lingala Sindhu (23K91A05D3), Padige Ajay (23K91A05H8), Mahek Ansari (23K91A05D8), Maheshwaram Hari Krishna (23K91A05D9). Guide: A Tejaswini.")
w("- Base paper (from the batch documents): C. Tran and S. Sakti, *SAM Translator*, IEEE Access vol. 14, pp. 2742-2752, 2026, doi 10.1109/ACCESS.2025.3644647.")
w("  mBART + self-paced learning + sparse mixture-of-experts (8 experts, top-2; 611M vs 1.7B parameters) + data-augmented self-training; BLEU on CVSS-C and CoVoST-2.")
w("  **StoryVox implements none of these techniques**; it is a cascade of pretrained models. Numbers are not comparable (SAM: BLEU; StoryVox: TTS-to-ASR WER/CER and RTF).")
w("- Supporting references: OmniVoice (arXiv 2604.00688: 646 languages, avg CER 4.00%, RTF 0.0319), MultiGen (arXiv 2508.08715).")
w("  `archived_base_papers/BASEPAPER_REFERENCES.md` names OmniVoice as base paper - this conflicts with the batch documents; SAM Translator was used.")
w()
w("## 2. Architecture")
w("- UI: React 19 + Vite, five pages (Landing, Studio, History, Story detail, Evaluation).")
w("- API: FastAPI + Uvicorn, 11 routes + SPA fallback: GET /api/health, /api/languages, /api/meta, /api/stories, /api/stories/{id}, /api/audio/{id}, /api/evaluations;")
w("  POST /api/stories/generate, /api/stories/{id}/synthesize, /api/evaluations/run; DELETE /api/stories/{id}.")
w("- Storage: SQLite `data/storyvox.db` (tables stories, audio_outputs, evaluations); WAV in `data/audio/`; evaluation JSON/CSV in `data/evaluations/`.")
w("- Story model: `Qwen/Qwen3-0.6B` (transformers text-generation pipeline, raw prompt, no chat template); max_new_tokens 220/420/700 for Short/Medium/Long; temperature 0.8, top_p 0.9;")
w("  offline composer `storyvox-local-fallback-v1` when output < 20 words or the pipeline fails.")
w("- Narration: `TTSProvider` ABC; `MMSTTSProvider` (VITS `facebook/mms-tts-*`, 16 kHz, 380-char chunks, peak-normalise 0.9, 0.25 s pause) then `SystemTTSProvider` (pyttsx3 / OS voice).")
w("- Evaluation: Whisper-small ASR, multilingual MiniLM similarity (TF-IDF proxy if unavailable), jiwer WER/CER, ROUGE-L, RTF = synthesis time / audio duration.")
w("- Configuration: 15 languages (en hi es fr de it pt ru ar tr nl pl zh ja ko), 8 styles, 3 lengths.")
w()
w("## 3. Honest gaps (objectives in the batch documents that the code does not implement)")
w("- No translation module (the story is generated directly in the target language).")
w("- No voice or speed selection (one fixed voice per language; `rate` only applies to the OS fallback).")
w("- No user rating / coherence feedback collection.")
w("- No reference-audio / voice cloning upload.")
w("- Checkpoints `facebook/mms-tts-ita`, `-cmn`, `-jpn` do not exist on the Hugging Face Hub: Italian, Chinese and Japanese fall back to the OS voice (English David/Zira only on the test machine).")
w("- `ffmpeg` is an undeclared dependency: without it Whisper cannot read the WAV and WER/CER are null (as in the evaluation JSON that shipped with the repo).")
w("- Korean needs the `uroman` package, which `requirements.txt` does not list.")
w("- The project `.venv` was created on another machine (points to a missing Python 3.14) and D: had ~1.5 GB free, so all runs used system Python 3.11.9 (torch 2.14.1, transformers 5.20.2).")
w()
w("## 4. Experimental setup")
if tts:
    w(f"- Machine: Intel Core i5-12500 (12 logical threads), 15.7 GB RAM, CPU only (device = {tts['device']}), torch {tts['torch']}.")
    w(f"- Data: {tts['dataset']}.")
    w(f"- ASR: {tts['asr_model']} (load {tts.get('asr_load_s')} s). TTS: {tts['tts_models']}.")
    w("- WER/CER reported two ways: *raw* (the app's own `wer()`; no normalisation) and *normalised* (NFKC, lower-case, punctuation removed; spaces removed for zh/ja). WER is not reported for zh/ja.")
w()
w("## 5. TTS -> ASR round trip (10 FLEURS sentences per language)")
if tts:
    w()
    w("| Lang | Checkpoint | Voice used | Narrated | Load (s) | Mean audio (s) | Mean synth (s) | Mean RTF | WER norm | CER norm | WER raw | CER raw |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for code, e in tts["languages"].items():
        voice = ", ".join(e.get("models_used", [])) or "none"
        narr = e.get("narrated", e.get("scored", 0) if e.get("models_used") else 0)
        w(f"| {code} | {e['checkpoint']} | {voice} | {narr}/{e['n']} | {f(e.get('mms_load_s'), 2)} | {f(e.get('mean_duration_s'), 2)} | {f(e.get('mean_synth_s'), 2)} | "
          f"{f(e.get('mean_rtf'), 4)} | {f(e.get('wer_norm_corpus'), 4)} | {f(e.get('cer_norm_corpus'), 4)} | {f(e.get('wer_raw_mean'), 4)} | {f(e.get('cer_raw_mean'), 4)} |")
    mms = [e for e in tts["languages"].values() if "facebook/mms" in " ".join(e.get("models_used", []))]
    if mms:
        rtfs = [e["mean_rtf"] for e in mms]
        cers = [e["cer_norm_corpus"] for e in mms if e.get("cer_norm_corpus") is not None]
        wers = [e["wer_norm_corpus"] for e in mms if e.get("wer_norm_corpus") is not None]
        w()
        w(f"- MMS languages scored: {len(mms)}. Mean RTF {sum(rtfs) / len(rtfs):.4f} (range {min(rtfs):.4f}-{max(rtfs):.4f}). Mean normalised CER {sum(cers) / len(cers):.4f} "
          f"(best {min(cers):.4f}, worst {max(cers):.4f}); mean normalised WER {sum(wers) / len(wers):.4f}.")
    w("- WER/CER here mix the TTS error and Whisper-small's own error; Whisper's error floor on natural speech was not measured separately.")
w()
w("## 6. Story generation (17 prompts x 3 conditions, idea fixed, Short length)")
if story:
    w(f"- Model {story['story_model']}, idea: \"{story['idea']}\", max_new_tokens {story['max_new_tokens']}, T={story['temperature']}, top_p={story['top_p']}, seed {story['seed']}, model load {story.get('model_load_s')} s.")
    w("- A = shipped path (raw prompt); B = same prompt through the Qwen3 chat template (thinking off; not shipped); C = shipped offline composer.")
    if story.get("summary"):
        w()
        w("| Condition | n | Latency (s) | Words | tok/s | Language match | Instr. echo | Distinct-2 | Prompt sim. | ROUGE-L |")
        w("|---|---|---|---|---|---|---|---|---|---|")
        for c, s in story["summary"].items():
            w(f"| {c} | {s['n']} | {f(s['mean_latency_s'], 2)} | {f(s['mean_words'], 1)} | {f(s['mean_tok_per_s'], 2) if not c.startswith('C_') else 'n/a'} | {f(s['language_match_rate'], 3)} | "
              f"{f(s['mean_instruction_echo'], 3)} | {f(s['mean_distinct_2'], 3)} | {f(s['mean_similarity'], 3)} | {f(s['mean_rougeL'], 3)} |")
    if story.get("length_scaling"):
        w()
        w("| Length | max_new_tokens | Generation (s) | Words | Audio (s) | Narration (s) | RTF | Total (s) |")
        w("|---|---|---|---|---|---|---|---|")
        for r in story["length_scaling"]:
            w(f"| {r['length']} | {r['max_new_tokens']} | {r['gen_s']} | {r['words']} | {r['audio_s']} | {r['tts_s']} | {r['rtf']} | {r['total_s']} |")
    w()
    w("- Prompt-story similarity is high for the offline composer because it quotes the idea verbatim - an artefact, not quality.")
w()
w("## 7. API timing (running server, 127.0.0.1)")
if api:
    w("| Endpoint | n | median ms | p95 ms | min | max |")
    w("|---|---|---|---|---|---|")
    for n, e in api["endpoints"].items():
        w(f"| {n} | {e['n']} | {e['median_ms']} | {e['p95_ms']} | {e['min_ms']} | {e['max_ms']} |")
    w()
    w("| # | Language | Style | Length | HTTP | Request (s) | Words | Gen (s) | Audio (s) | Narration (s) | RTF | Model | Cold |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in api["generate"]:
        w(f"| {r['order']} | {r['language']} | {r['style']} | {r['length']} | {r['http_status']} | {r['request_s']} | {r.get('words')} | {r.get('story_gen_s')} | {r.get('audio_s')} | {r.get('tts_s')} | {r.get('rtf')} | {r.get('tts_model')} | {r['cold']} |")
w()
w("## 7b. Story-length narration intelligibility (chunked Whisper on the stories the API generated)")
if sasr:
    w("The application's own evaluation transcribes with a plain pipeline call; for narration longer than 30 s transformers 5.x raises 'more than 3000 mel input features', so the evaluation JSON")
    w("holds `asr_error` and WER/CER are null for every story-length sample (reproduced: 5 of 5 samples in the run that fed the Evaluation screen). Here the same WAV files are transcribed with chunk_length_s=30.")
    w()
    w("| Story | Requested lang | Text actually in | Length | Words | Voice | Audio (s) | WER norm | CER norm |")
    w("|---|---|---|---|---|---|---|---|---|")
    for r in sorted(sasr["rows"], key=lambda r: r["story_id"]):
        w(f"| {r['story_id']} | {r['language']} | {r.get('text_language')} | {r['length']} | {r['words']} | {r['tts_model']} | {r['audio_s']} | {r['wer_norm']} | {r['cer_norm']} |")
    en = [r for r in sasr["rows"] if r["language"] == "en"]
    if en:
        w()
        w(f"- English stories (n={len(en)}): mean WER {sum(r['wer_norm'] for r in en) / len(en):.3f}, mean CER {sum(r['cer_norm'] for r in en) / len(en):.3f}.")
    w(f"- Stories requested in a non-English language whose text was detected as English: {sum(1 for r in sasr['rows'] if r['language'] != 'en' and r.get('text_language') == 'en')} of {sum(1 for r in sasr['rows'] if r['language'] != 'en')}.")
w()
w("## 8. Automated tests")
if tests:
    w(f"- pytest: {tests['passed']} passed, {tests['failed']} failed in {tests['seconds']} s (Python {tests['python']}). Summary line: {tests['summary_line']}.")
    for fn, d in tests["by_file"].items():
        w(f"  - {fn}: {d['passed']}/{d['total']}")
w()
w("## 9. Code size")
src = {"app (python)": list((ROOT / "app").rglob("*.py")), "tests": list((ROOT / "tests").glob("*.py")),
       "frontend src": [p for p in (ROOT / "frontend" / "src").rglob("*") if p.suffix in (".jsx", ".js", ".css")]}
for k, files in src.items():
    n = sum(len(p.read_text(encoding="utf-8", errors="ignore").splitlines()) for p in files)
    w(f"- {k}: {len(files)} files, {n} lines")
req = (ROOT / "requirements.txt").read_text(encoding="utf-8").splitlines()
w(f"- requirements.txt: {len([r for r in req if r.strip() and not r.startswith('#')])} packages")
w()
w("## 10. Screenshot inventory (docs/screenshots, 1440x900 viewport)")
shots = sorted((DOCS / "screenshots").glob("*.png"))
for p in shots:
    w(f"- {p.name} ({p.stat().st_size // 1024} KB)")
w(f"- Total: {len(shots)}")
w()
w("## 11. Diagrams (docs/diagrams)")
for p in sorted((DOCS / "diagrams").glob("*.png")):
    w(f"- {p.name}")
w()
w("## 12. Figures (docs/figures)")
for p in sorted((DOCS / "figures").glob("*.png")) if (DOCS / "figures").exists() else []:
    w(f"- {p.name}")
(DOCS / "REPORT_FACTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote", DOCS / "REPORT_FACTS.md", len(L), "lines")
