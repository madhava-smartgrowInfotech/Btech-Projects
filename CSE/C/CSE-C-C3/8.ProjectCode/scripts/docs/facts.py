def abl(share, trust, strat, metric, stat="mean"):
    return ABL[str(share)]["trust_on" if trust else "trust_off"][strat][metric][stat]


def lat(endpoint_prefix, key="mean_ms"):
    for k, v in LAT["endpoints"].items():
        if k.startswith(endpoint_prefix):
            return v[key]
    raise KeyError(endpoint_prefix)


