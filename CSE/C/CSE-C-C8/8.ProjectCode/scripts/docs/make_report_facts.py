"""Writes docs/REPORT_FACTS.md from docs/metrics/*.json so the facts file and the documents cannot drift apart.

    python -m scripts.docs.make_report_facts      # from 8.ProjectCode
"""

import os

from . import facts as F

SHOT_DESC = {
    "01_landing_dark": "Landing page, dark theme (WebGL hero, product pitch)",
    "02_landing_how_it_works_dark": "Landing page, scrolled to the how-it-works section",
    "03_landing_light": "Landing page, light theme",
    "04_dashboard": "Dashboard: reviewer count, stored analyses, decision-model accuracy with synthetic-data warning, recent analyses",
    "05_analyze_empty": "Analyze page before upload",
    "06_analyze_result_overview": "Analyze page after a real analysis: KPI tiles, paper overview, preliminary assessment, decision signal, AI review status",
    "07_result_review": "Result, Review tab: strengths, concerns, recommendations, coverage, AI synthesis",
    "08_result_literature": "Result, Literature tab: OpenAlex related works with relevance",
    "09_result_reviewers": "Result, Reviewers tab: ranked reviewers with score breakdown",
    "10_result_audit": "Result, Audit and export tab",
    "11_reviewers": "Reviewer directory",
    "12_reviewers_add_modal": "Add-reviewer dialog",
    "13_model_performance": "Model performance page: metrics, confusion matrix, synthetic-data warning",
    "14_history": "Analysis history",
    "15_saved_analysis": "A saved analysis reopened from history",
    "16_about": "About and responsible use",
    "17_dashboard_light": "Dashboard, light theme",
}


def main():
    L = []
    w = L.append
    sh, mm, tf = F.SHIPPED, F.MINILM, F.TFIDF
    w(f"# REPORT_FACTS - {F.PRODUCT} (CSE-C-C8)\n")
    w("Generated by `python -m scripts.docs.make_report_facts` from `docs/metrics/metrics.json`, `latency.json`, `tests.json`. Every document agrees with this file.\n")
    w("## 1. Project\n")
    w(f"- Title: {F.FULL_TITLE}\n- Product: {F.PRODUCT}; batch {F.BATCH_NO} ({F.SECTION}); API port {F.API_PORT}, web port {F.WEB_PORT}")
    w("- Team: " + "; ".join(f"{n} ({r})" for n, r in F.STUDENTS) + f"; guide {F.GUIDE}")
    w(f"- Base paper: {F.BASE_PAPER}")
    w("- Code size (lines): " + ", ".join(f"{k} {v}" for k, v in F.LOC.items()))
    e = F.ENV
    w(f"- Measured on: {e['cpu']}, {e['ram_gb']} GB RAM, {e['gpu']}, {e['os']}, Python {e['python']}; " + ", ".join(f"{k} {v}" for k, v in e["packages"].items() if v and k in ("scikit-learn", "torch", "transformers", "sentence-transformers", "fastapi", "PyMuPDF")))
    w("\n## 2. Architecture (from the code)\n")
    w("PDF -> PyMuPDF extraction (`pdf_extract`) -> features (`features`) -> decision signal (`ml_predict`) -> review (`review_synthesis`, local Qwen2.5-1.5B via `llm_service`) -> OpenAlex literature (`literature`) -> reviewer matching (`matching`, `embeddings`) -> SQLite `analyses` -> JSON/PDF export (`export_service`).")
    w("Match score = 0.55 expertise + 0.20 keyword + 0.15 method/topic + 0.10 availability - 0.60 conflict penalty (x100, clipped 0-100); bands Strong>=65, Good>=45, Possible>=25, Weak.")
    w("Endpoints: GET /api/health; GET /api/model/metrics; GET,POST /api/reviewers; PUT,DELETE /api/reviewers/{id}; GET /api/reviewers/export/csv; POST /api/reviewers/import; POST /api/analyze; GET /api/analyses; GET /api/analyses/{id}; GET /api/analyses/{id}/export?format=json|pdf.")
    w("Tables: `reviewers` (11 columns), `analyses` (9 columns, result_json blob); no foreign key.\n")
    w("## 3. Dataset facts\n")
    w(f"- `data/processed_dataset.csv`: {F.DM['rows']} rows, source `synthetic-fallback` (generated by `scripts/prepare_dataset.py`, seed 42; the PeerRead probe URL returned no usable data). Licence: generated by the project, no third-party data.")
    w(f"- Classes: {F.DM['class_counts']}. Split 80/20 stratified (seed 42): {F.DM['train']} train / {F.DM['test']} test.")
    g = F.GEN
    w(f"- Label construction: strength-phrase papers n={g['strong_phrase_papers']['n']} {g['strong_phrase_papers']['label_counts']}; weakness-phrase papers n={g['weak_phrase_papers']['n']} {g['weak_phrase_papers']['label_counts']}; best accuracy any text rule can reach = {g['best_possible_accuracy_from_phrases']}.")
    w("- Reviewer data: 6 seeded demo profiles (`app/services/seed.py`); matching probe set: 40 team-written abstracts (`scripts/eval_data.py`).\n")
    w("## 4. Decision-model metrics (shipped artifacts re-evaluated; equal to models/metrics.json: " + str(F.DM["matches_saved_metrics_json"]) + ")\n")
    w("| Metric | Value |\n|---|---|")
    for k in ("accuracy", "precision_macro", "recall_macro", "f1_macro", "roc_auc"):
        w(f"| {k} | {sh[k]} |")
    w(f"\nConfusion matrix (rows true accept/borderline/reject): {sh['confusion_matrix']}")
    w("\n| Class | Precision | Recall | F1 | Support |\n|---|---|---|---|---|")
    for k, v in F.PER_CLASS.items():
        w(f"| {k} | {v['precision']} | {v['recall']} | {v['f1']} | {v['support']} |")
    d = F.DM["decisive_only"]
    w(f"\nAccept-vs-reject only: {d['correct']}/{d['n']} = {d['accuracy']}. Borderline row: {F.DM['borderline_row']}.")
    w("\n| Baseline | Accuracy | Macro F1 | ROC-AUC |\n|---|---|---|---|")
    for k, v in F.BASELINES.items():
        w(f"| {k} | {v['accuracy']} | {v['f1_macro']} | {v.get('roc_auc', '-')} |")
    s = F.SEEDS
    w(f"\nFive splits: accuracy {s['accuracy']['mean']} +/- {s['accuracy']['sd']} (min {s['accuracy']['min']}, max {s['accuracy']['max']}); macro F1 {s['f1_macro']['mean']} +/- {s['f1_macro']['sd']}; ROC-AUC {s['roc_auc']['mean']} +/- {s['roc_auc']['sd']}.")
    w("\nConfidence threshold: " + "; ".join(f"t={r['threshold']}: keep {r['coverage']} acc {r['accuracy_on_kept']}" for r in F.THR))
    w("\n## 5. Reviewer matching (40 probe abstracts, 6 demo reviewers)\n")
    w("| Configuration | MiniLM top-1 | top-3 | MRR | TF-IDF top-1 | top-3 | MRR |\n|---|---|---|---|---|---|---|")
    for k in ("full_hybrid_shipped_weights", "semantic_similarity_only", "lexical_only_keyword_and_method", "hybrid_without_availability"):
        a, b = mm[k], tf[k]
        w(f"| {k} | {a['top1']} | {a['top3']} | {a['mrr']} | {b['top1']} | {b['top3']} | {b['mrr']} |")
    w(f"\nRandom top-1 expectation {mm['random_expectation_top1']}; top-3 {mm['random_expectation_top3']}. Misses (MiniLM hybrid): {[ (m['expected'], m['got']) for m in mm['top1_misses_shipped']]}.")
    c = mm["conflict"]
    w(f"Conflict injection: {c['detected_by_kind']}; false flags on {c['clean_pairs_checked']} clean pairs: {c['false_flags_on_clean_papers']}.")
    w("Scaling (median ms per ranking): MiniLM " + ", ".join(f"{r['pool']} reviewers {r['median_ms']}" for r in mm["scaling_ms"]) + "; TF-IDF " + ", ".join(f"{r['pool']}: {r['median_ms']}" for r in tf["scaling_ms"]))
    w("\n## 6. Real PDFs through the pipeline\n")
    w("| File | Pages | Words | Structural | Decision signal | Sections found | Title extracted |\n|---|---|---|---|---|---|---|")
    for r in F.REAL:
        w(f"| {r['file'][:48]} | {r['pages']} | {r['words']} | {r['structural_score']} | {r['ml_label']} ({r['ml_confidence']}) | {len(r['sections_detected'])} | {r['title_extracted'][:50]} |")
    w("\n## 7. Latency and tests\n")
    L_ = F.LATENCY
    if L_:
        w(f"- Embedding model load {L_.get('embedding_model_load_s')} s; local LLM load {L_.get('llm_load_s')} s (cached on disk).")
        for k, v in (L_.get("pipeline_stages") or {}).items():
            w(f"- {k}: " + ", ".join(f"{a} {b}" for a, b in v.items()))
        w(f"- HTTP with local LLM on (seconds): {L_.get('http_llm_on_s')}")
        for k, v in (L_.get("http_api") or {}).items():
            w(f"- HTTP {k}: {v}")
    w(f"- pytest: {F.PYTEST_PASSED}/{F.PYTEST_TOTAL} passed in {F.PYTEST_SECONDS} s (LLM disabled); smoke test: {F.SMOKE_PASSED}/{F.SMOKE_TOTAL} checks passed.")
    w("- Literature (OpenAlex) latency: " + ", ".join(f"{r['ms']} ms ({r['status']})" for r in F.LIT))
    w("\n## 8. Screenshot inventory (docs/screenshots, 1440x900 unless full-page height)\n")
    for f in sorted(os.listdir(F.SHOTS)):
        if f.endswith(".png"):
            w(f"- `{f}` - {SHOT_DESC.get(f[:-4], '')}")
    w("\n## 9. Defects found while measuring (documented, not fixed in this run)\n")
    w("- OpenAlex returns HTTP 400 when the extracted title contains a question mark (`?`): the survey PDF's title gives `literature_retrieval_status = unavailable`; the query string is not sanitised.")
    w("- Section detection does not recognise roman-numeral headings (`I. INTRODUCTION`); the IEEE base paper PDF reports no introduction and its title heuristic returns the DOI line.")
    w("- The coverage chart's Novelty value is a fixed 55; novelty is not measured.")
    w("- Analysis timestamps are stored as naive UTC (`datetime.utcnow`) and shown by the UI without a zone, so they read about 5.5 hours behind local time (IST).")
    w("- A corrupt PDF that still starts with `%PDF` returns HTTP 200 with almost no extracted text (and the short-text warning); a reviewer CSV without display names imports 0 rows without an error.")
    w("- The TF-IDF fallback vocabulary is fitted once on the first request and then frozen.")
    w("- Conflict detection is literal string matching: paraphrased affiliations and first-name-only mentions are missed.")
    w("\n## 10. Not measured (stated as gaps)\n")
    w("- Accuracy on real peer-review decisions; reviewer-assignment quality against independent expert judgement or against real conference assignments; a user study; behaviour on scanned (image-only) PDFs; GPU performance; multi-user load; LLM review quality (no human rating was collected).")
    open(os.path.join(F.DOCS, "REPORT_FACTS.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote docs/REPORT_FACTS.md", len(L), "lines")


if __name__ == "__main__":
    main()
